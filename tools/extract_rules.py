#!/usr/bin/env python3
"""Copies the shared football rules module (FBS + the Ultimate Team ratings) out of the game file into the Worker,
so the browser and the server run the SAME code. Run after any change to that block:
    python3 -I extract_rules.py <ultimate-sports.html> <backend/src/fbs_rules.js>"""
import sys,re,hashlib
src,dst=sys.argv[1],sys.argv[2]
s=open(src,encoding='utf-8').read()
a=s.index("(function(root){\n  const clamp=(v,a,b)=>Math.max(a,Math.min(b,v)),len=")
e=s.index("})(globalThis);",a)+len("})(globalThis);")
block=s[a:e]
h=hashlib.sha256(block.encode()).hexdigest()[:12]
out=("// GENERATED by tools/extract_rules.py from the game file - do not edit by hand. Rules hash: "+h+"\n"
     "const root = {};\n"+block.replace("})(globalThis);","})(root);")+"\n"
     "export const FBS = root.UltimateFootballRules;\nexport const UFR = root.UltimateFootballRatings;\nexport const RULES_HASH = '"+h+"';\n")
open(dst,'w',encoding='utf-8').write(out); print('rules hash',h,len(out),'bytes')

# ---- the player ratings the Worker needs (the same spreadsheet data the game was built from) ----
if len(sys.argv) > 3:
    import json
    i=s.index('window.FB_PLAYER_DB=')+len('window.FB_PLAYER_DB=')
    db,_=json.JSONDecoder().raw_decode(s[i:i+30000000])
    keep=['id','name','pos','tier','team','jersey','height_in','weight_lb','game_weight_lb','overall','attributes']
    rows={p['id']:dict({k:p.get(k) for k in keep},appearance={k:p['appearance'].get(k) for k in ('skin_hex','jersey_hex','accent_hex','helmet_hex')}) for p in db}
    open(sys.argv[3],'w',encoding='utf-8').write("// GENERATED by tools/extract_rules.py from the player database. The server rates players from THIS, never from anything the browser sends.\nexport const PLAYERS = "+json.dumps(rows,separators=(',',':'),ensure_ascii=False)+";\n")
    print('players',len(rows))
